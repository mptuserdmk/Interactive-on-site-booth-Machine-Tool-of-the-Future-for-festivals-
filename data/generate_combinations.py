def generate():
    combinations = []
    combo_id = 1
    
    for el in ELEMENTS:
        for pwr in POWERS:
            base_info = MATRIX[(el["id"], pwr["id"])]
            for col in COLORS:
                combo = {
                    "id": combo_id,
                    "element": el["id"],
                    "element_name": el["name"],
                    "element_icon": el["icon"],
                    "power": pwr["id"],
                    "power_name": pwr["name"],
                    "power_desc": pwr["desc"],
                    "color": col["id"],
                    "color_name": col["name"],
                    "color_hex": col["hex"],
                    "color_glow": col["glow"],
                    "machine_name": base_info["title"],
                    "description": base_info["desc"],
                    "location": base_info["location"],
                    "prompt_theme": f"{el['theme_desc']}, aesthetic accent color {col['name']} ({col['hex']})"
                }
                combinations.append(combo)
                combo_id += 1

    out_file = Path(__file__).resolve().parent / "combinations.json"
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(combinations, f, ensure_ascii=False, indent=2)
    
    print(f"Successfully generated {len(combinations)} combinations to {out_file}")

if __name__ == "__main__":
    generate()
